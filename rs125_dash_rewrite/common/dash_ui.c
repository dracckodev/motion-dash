/* ── Cell layout helper ──────────────────────────────────────────────────── */
/* Positions label+value+unit horizontally centred on (cx,cy).
   Unit is placed at bottom-right of value with UNIT_OFFSET_Y = -4 */
#define UNIT_OFFSET_Y (-4)
static void position_cell(lv_obj_t *lbl, lv_obj_t *val, lv_obj_t *unit,
                           int cx, int cy) {
    int wl = lbl  ? lv_obj_get_width(lbl)  : 0;
    int wv = val  ? lv_obj_get_width(val)  : 0;
    int wu = unit ? lv_obj_get_width(unit) : 0;
    int hl = lbl  ? lv_obj_get_height(lbl)  : 0;
    int hv = val  ? lv_obj_get_height(val)  : 0;
    int hu = unit ? lv_obj_get_height(unit) : 0;
    int gap = 8;
    int w_total = wl + (wl?gap:0) + wv + (wu?5+wu:0);
    int x = cx - w_total/2;
    if (lbl)  { lv_obj_set_pos(lbl,  x, cy - hl/2); x += wl + gap; }
    if (val)  { lv_obj_set_pos(val,  x, cy - hv/2); }
    if (unit) { lv_obj_set_pos(unit, x + wv + 5,
                    cy + hv/2 - hu + UNIT_OFFSET_Y); }
}

/* ── Tick label positions ─────────────────────────────────────────────────── */
static lv_obj_t *tick_labels[5];
static const float tick_rpms_lbl[5] = {2000,4000,6000,8000,10000};
static const char *tick_strs[5]     = {"2","4","6","8","10"};
static const float tick_ox[5] = {0,0,-4,-4,-4};
static const float tick_oy[5] = {0,0,3.5f,3.5f,3.5f};

/* ── Full update ─────────────────────────────────────────────────────────── */
void dash_ui_update(const dash_state_t *s) {
    if (s->rebuild_hex)
        dash_ui_rebuild_hex(s);

    cache_theme(s->theme_idx);

    /* -- arc band -- */
    draw_arc_band_canvas(s->disp_rpm);

    /* -- tick label colours & positions -- */
    uint32_t tw = g_tick_contrast ?
        (0xFF000000|((255-(u_WHITE>>16&0xFF))<<16)|((255-(u_WHITE>>8&0xFF))<<8)|(255-(u_WHITE&0xFF))) : u_WHITE;
    for (int ti=0;ti<5;ti++) {
        if (!tick_labels[ti]) {
            tick_labels[ti] = lv_label_create(lv_screen_active());
            lv_obj_set_style_text_font(tick_labels[ti], &font_roboto_bolditalic_20, 0);
            lv_label_set_text(tick_labels[ti], tick_strs[ti]);
        }
        float a = rpm_angle(tick_rpms_lbl[ti]);
        float lx,ly;
        tick_label_xy(a,&lx,&ly);
        lx += TICK_LABEL_GLOBAL_OX + tick_ox[ti];
        ly += TICK_LABEL_GLOBAL_OY + tick_oy[ti];
        float t_val = (s->disp_rpm - tick_rpms_lbl[ti] + TICK_LIGHT_WIDTH_RPM)
                    / (2.0f * TICK_LIGHT_WIDTH_RPM);
        if (t_val<0) t_val=0; if (t_val>1) t_val=1;
        lv_color_t col = lerp_col(u_RED, tw, t_val);
        lv_obj_set_style_text_color(tick_labels[ti], col, 0);
        int tw2 = lv_obj_get_width(tick_labels[ti]);
        int th  = lv_obj_get_height(tick_labels[ti]);
        lv_obj_set_pos(tick_labels[ti], (int32_t)(lx - tw2/2), (int32_t)(ly - th/2));
    }

    /* -- speed -- */
    char spd_buf[8]; snprintf(spd_buf, sizeof(spd_buf), "%d", (int)s->disp_speed);
    lv_label_set_text(lbl_speed, spd_buf);
    lv_color_t spd_col = s->blink_on ? lv_color_make(255,49,49) : c_WHITE;
    lv_color_t kmh_col = s->blink_on ? lv_color_make(255,49,49) : c_GREY;
    lv_obj_set_style_text_color(lbl_speed, spd_col, 0);
    lv_obj_set_style_text_color(lbl_kmh,   kmh_col, 0);
    /* position: right-align speed to x=683, vcenter at y=233 */
    int sw = lv_obj_get_width(lbl_speed);
    int sh = lv_obj_get_height(lbl_speed);
    lv_obj_set_pos(lbl_speed, 683 - sw, 233 - sh/2);
    int uw = lv_obj_get_width(lbl_kmh);
    int uh = lv_obj_get_height(lbl_kmh);
    lv_obj_set_pos(lbl_kmh, 682, 271 - uh/2);

    /* -- gear -- */
    lv_label_set_text(lbl_gear_val, s->gear);
    lv_color_t gc = (s->gear[0]=='N') ? c_RED : c_WHITE;
    lv_obj_set_style_text_color(lbl_gear_val, gc, 0);
    int gw = lv_obj_get_width(lbl_gear_val);
    int gh = lv_obj_get_height(lbl_gear_val);
    lv_obj_set_pos(lbl_gear_val, 86 - gw/2, 127 - gh/2);

    /* -- strip separators -- */
    set_line(line_row1, STRIP_L, ROW1_Y, W,      ROW1_Y);
    set_line(line_row2, 0,       ROW2_Y, W,      ROW2_Y);
    set_line(line_va,   VCOL_A,  ROW1_Y, VCOL_A, ROW2_Y);
    set_line(line_vb,   VCOL_B,  ROW1_Y, VCOL_B, ROW2_Y);
    set_line(line_vc,   VCOL_C,  ROW2_Y, VCOL_C, H);
    set_line(line_vd,   VCOL_D,  ROW2_Y, VCOL_D, H);

    /* -- ODO / TRIP -- */
    static const char *odo_labels[3] = {"ODO","TRIP A","TRIP B"};
    char odo_val_buf[16];
    double odo_val = (s->odo_mode==0)?s->odo:(s->odo_mode==1)?s->trip_a:s->trip_b;
    snprintf(odo_val_buf, sizeof(odo_val_buf), "%.2f", odo_val);
    lv_label_set_text(lbl_odo_label, odo_labels[s->odo_mode]);
    lv_label_set_text(lbl_odo_val,   odo_val_buf);
    lv_label_set_text(lbl_odo_unit,  "km");
    int cy1 = (ROW1_Y + ROW2_Y)/2;
    position_cell(lbl_odo_label, lbl_odo_val, lbl_odo_unit, (STRIP_L+VCOL_A)/2, cy1);

    /* -- TEMP -- */
    char temp_buf[8]; snprintf(temp_buf,sizeof(temp_buf),"%d",(int)s->temp);
    lv_label_set_text(lbl_temp_val, temp_buf);
    /* reuse odo_label slot for "TEMP" text — create separate static label */
    /* (icon_temp not available in LVGL ver — use text label "TEMP") */
    position_cell(NULL, lbl_temp_val, NULL, (VCOL_A+VCOL_B)/2, cy1);

    /* -- VOLT -- */
    char volt_buf[8]; snprintf(volt_buf,sizeof(volt_buf),"%.1f",s->volt);
    lv_label_set_text(lbl_volt_val, volt_buf);
    position_cell(NULL, lbl_volt_val, NULL, (VCOL_B+W)/2, cy1);

    /* -- RANGE -- */
    char range_buf[8]; snprintf(range_buf,sizeof(range_buf),"%d",s->range);
    lv_label_set_text(lbl_range_val, range_buf);
    int cy2 = (ROW2_Y + H)/2;
    position_cell(NULL, lbl_range_val, NULL, (STRIP_L+VCOL_C)/2, cy2);

    /* -- ECO -- */
    char eco_buf[12], eco_unit_buf[12];
    if (s->eco_imperial) {
        float mpg = s->eco > 0 ? 282.5f / s->eco : 0;
        snprintf(eco_buf,  sizeof(eco_buf),  "%.1f", mpg);
        snprintf(eco_unit_buf, sizeof(eco_unit_buf), "mpg");
    } else {
        snprintf(eco_buf,  sizeof(eco_buf),  "%d", s->eco);
        snprintf(eco_unit_buf, sizeof(eco_unit_buf), "L/100km");
    }
    lv_label_set_text(lbl_eco_val,  eco_buf);
    lv_label_set_text(lbl_eco_unit, eco_unit_buf);
    position_cell(NULL, lbl_eco_val, lbl_eco_unit, (VCOL_C+VCOL_D)/2, cy2);

    /* -- TIME -- */
    lv_label_set_text(lbl_time, s->time_str);
    int tw3 = lv_obj_get_width(lbl_time);
    int th3 = lv_obj_get_height(lbl_time);
    lv_obj_set_pos(lbl_time, (VCOL_D+W)/2 - tw3/2, cy2 - th3/2);

    /* -- dim overlay -- */
    lv_opa_t dim_opa = (s->brightness < 1.0f)
        ? (lv_opa_t)((1.0f - s->brightness) * 255)
        : LV_OPA_TRANSP;
    lv_obj_set_style_bg_opa(dim_overlay, dim_opa, 0);
}
