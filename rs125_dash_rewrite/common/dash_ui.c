/* ── Helpers ─────────────────────────────────────────────────────────────── */
static inline float rpm_angle(float rpm) {
    float frac = rpm / MAX_RPM;
    if (frac < 0) frac = 0;
    if (frac > 1) frac = 1;
    return ARC_A_START + frac * (ARC_A_END - ARC_A_START);
}

static inline lv_color_t u32_to_lvc(uint32_t c) {
    return lv_color_make((c>>16)&0xFF,(c>>8)&0xFF,c&0xFF);
}

static inline lv_color_t lerp_col(uint32_t a, uint32_t b, float t) {
    if (t < 0) t = 0; if (t > 1) t = 1;
    uint8_t r = (uint8_t)(((a>>16)&0xFF)*(1-t) + ((b>>16)&0xFF)*t);
    uint8_t g = (uint8_t)(((a>>8 )&0xFF)*(1-t) + ((b>>8 )&0xFF)*t);
    uint8_t bl= (uint8_t)(((a    )&0xFF)*(1-t) + ((b    )&0xFF)*t);
    return lv_color_make(r,g,bl);
}

/* Upper/lower arc sample points */
static void upper_xy(float deg, float *x, float *y) {
    float a = deg * (float)M_PI / 180.0f;
    *x = ARC_CX_O + ARC_R_UPPER * cosf(a);
    *y = ARC_CY_O + ARC_R_UPPER * sinf(a);
}
static void lower_xy(float deg, float *x, float *y) {
    float a = deg * (float)M_PI / 180.0f;
    *x = ARC_CX_I + ARC_R_LOWER * cosf(a);
    *y = ARC_CY_I + ARC_R_LOWER * sinf(a);
}
static void tick_label_xy(float deg, float *x, float *y) {
    float a = deg * (float)M_PI / 180.0f;
    *x = ARC_CX_I + TICK_LABEL_R * cosf(a);
    *y = ARC_CY_I + TICK_LABEL_R * sinf(a);
}

