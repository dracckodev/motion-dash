/* ── Hex grid ────────────────────────────────────────────────────────────── */
void dash_ui_rebuild_hex(const dash_state_t *s) {
    const dash_theme_t *t = &DASH_THEMES[s->theme_idx];
    lv_canvas_t *cv = (lv_canvas_t *)cv_hex;
    lv_layer_t layer;
    lv_canvas_init_layer(cv_hex, &layer);

    /* fill background */
    lv_draw_rect_dsc_t bg;
    lv_draw_rect_dsc_init(&bg);
    bg.bg_color = u32_to_lvc(t->BG);
    bg.bg_opa   = LV_OPA_COVER;
    lv_area_t full = {0, 0, W-1, H-1};
    lv_draw_rect(&layer, &bg, &full);

    /* hex cells */
    float R   = 27.0f;
    float dx  = R * sqrtf(3.0f);
    float dy  = R * 1.5f;
    uint32_t bg32 = t->BG;
    uint8_t br = ((bg32>>16)&0xFF)/3 + ((bg32>>8)&0xFF)/3 + (bg32&0xFF)/3;
    lv_color_t fill_col, outline_col;
    lv_opa_t   fill_opa, outline_opa;
    if (br < 128) {
        fill_col    = u32_to_lvc(t->RED_DARK);
        outline_col = u32_to_lvc(t->RED_MED);
        fill_opa    = 128; outline_opa = 128;
    } else {
        uint32_t fc = ((((bg32>>16)&0xFF)>15?(((bg32>>16)&0xFF)-15):0)<<16)|
                      ((((bg32>>8 )&0xFF)>15?(((bg32>>8 )&0xFF)-15):0)<<8)|
                       (((bg32    )&0xFF)>15?(((bg32    )&0xFF)-15):0);
        uint32_t oc = ((((bg32>>16)&0xFF)>30?(((bg32>>16)&0xFF)-30):0)<<16)|
                      ((((bg32>>8 )&0xFF)>30?(((bg32>>8 )&0xFF)-30):0)<<8)|
                       (((bg32    )&0xFF)>30?(((bg32    )&0xFF)-30):0);
        fill_col    = u32_to_lvc(fc);
        outline_col = u32_to_lvc(oc);
        fill_opa    = 210; outline_opa = 255;
    }

    lv_draw_rect_dsc_t cell_dsc;
    lv_draw_rect_dsc_init(&cell_dsc);
    cell_dsc.bg_color = fill_col; cell_dsc.bg_opa = fill_opa;
    cell_dsc.border_color = outline_col; cell_dsc.border_opa = outline_opa;
    cell_dsc.border_width = 1;

    int rows = (int)(H / dy) + 4;
    int cols = (int)(W / dx) + 4;
    for (int row = -1; row < rows; row++) {
        for (int ci = -1; ci < cols; ci++) {
            float hx = ci * dx + (row % 2 ? dx / 2.0f : 0.0f);
            float hy = row * dy;
            /* approximate hex as bounding rect — LVGL doesn't support
               arbitrary polygons in draw layer, use triangle pairs instead */
            lv_point_precise_t pts[6];
            for (int i = 0; i < 6; i++) {
                float a = (float)(60*i - 30) * (float)M_PI / 180.0f;
                pts[i].x = (int32_t)(hx + R * cosf(a));
                pts[i].y = (int32_t)(hy + R * sinf(a));
            }
            /* draw as filled polygon via triangle fan */
            lv_draw_triangle_dsc_t tri;
            lv_draw_triangle_dsc_init(&tri);
            tri.bg_color = fill_col; tri.bg_opa = fill_opa;
            for (int i = 1; i < 5; i++) {
                lv_point_precise_t tp[3] = {pts[0], pts[i], pts[i+1]};
                tri.p[0]=pts[0]; tri.p[1]=pts[i]; tri.p[2]=pts[i+1];
                lv_draw_triangle(&layer, &tri);
            }
            /* outline — draw 6 lines */
            lv_draw_line_dsc_t ld;
            lv_draw_line_dsc_init(&ld);
            ld.color = outline_col; ld.opa = outline_opa; ld.width = 1;
            for (int i = 0; i < 6; i++) {
                ld.p1 = pts[i]; ld.p2 = pts[(i+1)%6];
                lv_draw_line(&layer, &ld);
            }
        }
    }
    lv_canvas_finish_layer(cv_hex, &layer);
}

/* ── Arc band draw (onto cv_arc canvas each frame) ───────────────────────── */
static void draw_arc_band_canvas(float rpm) {
    lv_layer_t layer;
    lv_canvas_init_layer(cv_arc, &layer);

    /* clear transparent */
    lv_draw_rect_dsc_t clr;
    lv_draw_rect_dsc_init(&clr);
    clr.bg_color = lv_color_black(); clr.bg_opa = LV_OPA_TRANSP;
    lv_area_t full = {0,0,W-1,H-1};
    lv_draw_rect(&layer, &clr, &full);

    float target_a = rpm_angle(rpm);

    lv_draw_triangle_dsc_t td;
    lv_draw_triangle_dsc_init(&td);
    lv_draw_line_dsc_t ld;
    lv_draw_line_dsc_init(&ld);

    /* -- background (RED_DARK) band across full arc -- */
    td.bg_color = c_RED_DARK; td.bg_opa = LV_OPA_COVER;
    for (int i = 0; i < STEPS; i++) {
        float a0 = ARC_A_START + (float)i     / STEPS * (ARC_A_END - ARC_A_START);
        float a1 = ARC_A_START + (float)(i+1) / STEPS * (ARC_A_END - ARC_A_START);
        float ux0,uy0,ux1,uy1,lx0,ly0,lx1,ly1;
        upper_xy(a0,&ux0,&uy0); upper_xy(a1,&ux1,&uy1);
        lower_xy(a0,&lx0,&ly0); lower_xy(a1,&lx1,&ly1);
        /* quad as two triangles */
        td.p[0].x=(int32_t)ux0; td.p[0].y=(int32_t)uy0;
        td.p[1].x=(int32_t)ux1; td.p[1].y=(int32_t)uy1;
        td.p[2].x=(int32_t)lx1; td.p[2].y=(int32_t)ly1;
        lv_draw_triangle(&layer, &td);
        td.p[1].x=(int32_t)lx0; td.p[1].y=(int32_t)ly0;
        td.p[2].x=(int32_t)lx1; td.p[2].y=(int32_t)ly1;
        lv_draw_triangle(&layer, &td);
    }

    /* -- lit (RED) band up to target_angle -- */
    if (target_a > ARC_A_START + 1e-4f) {
        int n_lit = (int)ceilf(STEPS * (target_a - ARC_A_START) / (ARC_A_END - ARC_A_START));
        if (n_lit > STEPS) n_lit = STEPS;
        td.bg_color = c_RED;
        for (int i = 0; i < n_lit; i++) {
            float a0 = ARC_A_START + (float)i     / STEPS * (ARC_A_END - ARC_A_START);
            float a1 = ARC_A_START + (float)(i+1) / STEPS * (ARC_A_END - ARC_A_START);
            float ux0,uy0,ux1,uy1,lx0,ly0,lx1,ly1;
            upper_xy(a0,&ux0,&uy0); upper_xy(a1,&ux1,&uy1);
            lower_xy(a0,&lx0,&ly0); lower_xy(a1,&lx1,&ly1);
            td.p[0].x=(int32_t)ux0; td.p[0].y=(int32_t)uy0;
            td.p[1].x=(int32_t)ux1; td.p[1].y=(int32_t)uy1;
            td.p[2].x=(int32_t)lx1; td.p[2].y=(int32_t)ly1;
            lv_draw_triangle(&layer, &td);
            td.p[1].x=(int32_t)lx0; td.p[1].y=(int32_t)ly0;
            td.p[2].x=(int32_t)lx1; td.p[2].y=(int32_t)ly1;
            lv_draw_triangle(&layer, &td);
        }
    }

    /* -- upper outline -- */
    ld.color = c_RED; ld.opa = LV_OPA_COVER; ld.width = LINE_W;
    for (int i = 0; i < STEPS; i++) {
        float a0 = ARC_A_START + (float)i     / STEPS * (ARC_A_END - ARC_A_START);
        float a1 = ARC_A_START + (float)(i+1) / STEPS * (ARC_A_END - ARC_A_START);
        float x0,y0,x1,y1;
        upper_xy(a0,&x0,&y0); upper_xy(a1,&x1,&y1);
        ld.p1.x=(int32_t)x0; ld.p1.y=(int32_t)y0;
        ld.p2.x=(int32_t)x1; ld.p2.y=(int32_t)y1;
        lv_draw_line(&layer, &ld);
    }

    /* -- lower outline -- */
    ld.width = LINE_W > 1 ? LINE_W-1 : 1;
    for (int i = 0; i < STEPS; i++) {
        float a0 = ARC_A_START + (float)i     / STEPS * (ARC_A_END - ARC_A_START);
        float a1 = ARC_A_START + (float)(i+1) / STEPS * (ARC_A_END - ARC_A_START);
        float x0,y0,x1,y1;
        lower_xy(a0,&x0,&y0); lower_xy(a1,&x1,&y1);
        ld.p1.x=(int32_t)x0; ld.p1.y=(int32_t)y0;
        ld.p2.x=(int32_t)x1; ld.p2.y=(int32_t)y1;
        lv_draw_line(&layer, &ld);
    }

    /* -- major tick marks -- */
    static const float tick_rpms[5] = {2000,4000,6000,8000,10000};
    lv_color_t tick_lit = g_tick_contrast
        ? lv_color_make(255-(u_WHITE>>16&0xFF),255-(u_WHITE>>8&0xFF),255-(u_WHITE&0xFF))
        : c_WHITE;
    ld.width = LINE_W > 1 ? LINE_W/2 : 1;
    for (int ti = 0; ti < 5; ti++) {
        float tr = tick_rpms[ti];
        float a  = rpm_angle(tr);
        float ux,uy,lx,ly;
        upper_xy(a,&ux,&uy); lower_xy(a,&lx,&ly);
        float thickness = sqrtf((ux-lx)*(ux-lx)+(uy-ly)*(uy-ly));
        int out_len = (int)(fmaxf(4.0f,(thickness+6.0f)*0.5f));
        float t_val = (rpm - tr + TICK_LIGHT_WIDTH_RPM) / (2.0f * TICK_LIGHT_WIDTH_RPM);
        if (t_val<0) t_val=0; if (t_val>1) t_val=1;
        ld.color = lerp_col(u_RED, g_tick_contrast?
            (0xFF000000|(255-(u_WHITE>>16&0xFF))<<16|(255-(u_WHITE>>8&0xFF))<<8|(255-(u_WHITE&0xFF))) : u_WHITE,
            t_val);
        ld.p1.x=(int32_t)lx; ld.p1.y=(int32_t)ly;
        ld.p2.x=(int32_t)lx; ld.p2.y=(int32_t)(ly - out_len);
        lv_draw_line(&layer, &ld);
    }

    /* -- subtick marks -- */
    ld.width = 1;
    for (int tr = 500; tr < (int)MAX_RPM; tr += 500) {
        if (tr==2000||tr==4000||tr==6000||tr==8000||tr==10000) continue;
        float a = rpm_angle((float)tr);
        float lx,ly;
        lower_xy(a,&lx,&ly);
        int out_len = (tr % 1000 == 0) ? 18 : 10;
        float t_val = (rpm - tr + TICK_LIGHT_WIDTH_RPM) / (2.0f * TICK_LIGHT_WIDTH_RPM);
        if (t_val<0) t_val=0; if (t_val>1) t_val=1;
        uint32_t tw = g_tick_contrast?
            (0xFF000000|(255-(u_WHITE>>16&0xFF))<<16|(255-(u_WHITE>>8&0xFF))<<8|(255-(u_WHITE&0xFF))): u_WHITE;
        ld.color = lerp_col(u_RED, tw, t_val);
        ld.p1.x=(int32_t)lx; ld.p1.y=(int32_t)ly;
        ld.p2.x=(int32_t)lx; ld.p2.y=(int32_t)(ly - out_len);
        lv_draw_line(&layer, &ld);
    }

    lv_canvas_finish_layer(cv_arc, &layer);
}

/* ── Strip line helpers ───────────────────────────────────────────────────── */
static void set_line(lv_obj_t *obj, int x1,int y1,int x2,int y2) {
    static lv_point_precise_t pts[2];
    /* each line obj has its own static pts — use obj userdata trick:
       store pts inside lv_obj userdata to avoid aliasing */
    lv_point_precise_t *p = (lv_point_precise_t*)lv_obj_get_user_data(obj);
    if (!p) {
        p = lv_malloc(2*sizeof(lv_point_precise_t));
        lv_obj_set_user_data(obj, p);
    }
    p[0].x=x1; p[0].y=y1; p[1].x=x2; p[1].y=y2;
    lv_line_set_points(obj, p, 2);
}

/* ── UI init ─────────────────────────────────────────────────────────────── */
void dash_ui_init(void) {
    cache_theme(0);
    lv_obj_t *scr = lv_screen_active();
    lv_obj_set_style_bg_color(scr, c_BG, 0);
    lv_obj_set_style_bg_opa(scr, LV_OPA_COVER, 0);

    /* hex grid canvas */
    lv_draw_buf_init(&db_hex, W, H, LV_COLOR_FORMAT_RGB565, LV_STRIDE_AUTO, raw_hex, sizeof(raw_hex));
    cv_hex = lv_canvas_create(scr);
    lv_canvas_set_draw_buf(cv_hex, &db_hex);
    lv_obj_set_pos(cv_hex, 0, 0);

    /* arc canvas (ARGB so transparent outside arc region) */
    lv_draw_buf_init(&db_arc, W, H, LV_COLOR_FORMAT_ARGB8888, LV_STRIDE_AUTO, raw_arc, sizeof(raw_arc));
    cv_arc = lv_canvas_create(scr);
    lv_canvas_set_draw_buf(cv_arc, &db_arc);
    lv_obj_set_pos(cv_arc, 0, 0);

    /* strip separator lines */
    static lv_style_t line_style;
    lv_style_init(&line_style);
    lv_style_set_line_color(&line_style, c_RED);
    lv_style_set_line_width(&line_style, LINE_W);
    lv_style_set_line_opa(&line_style, LV_OPA_COVER);

    #define MKLINE(var) \
        var = lv_line_create(scr); \
        lv_obj_add_style(var, &line_style, 0);

    MKLINE(line_row1); MKLINE(line_row2);
    MKLINE(line_va);   MKLINE(line_vb);
    MKLINE(line_vc);   MKLINE(line_vd);

    /* gear circle */
    circle_gear = lv_obj_create(scr);
    lv_obj_set_size(circle_gear, CIRCLE_R*2, CIRCLE_R*2);
    lv_obj_set_pos(circle_gear, CIRCLE_CX - CIRCLE_R, CIRCLE_CY - CIRCLE_R);
    lv_obj_set_style_radius(circle_gear, CIRCLE_R, 0);
    lv_obj_set_style_bg_color(circle_gear, c_BG, 0);
    lv_obj_set_style_bg_opa(circle_gear, LV_OPA_COVER, 0);
    lv_obj_set_style_border_color(circle_gear, c_RED, 0);
    lv_obj_set_style_border_width(circle_gear, LINE_W, 0);
    lv_obj_set_style_border_opa(circle_gear, LV_OPA_COVER, 0);

    /* speed label */
    lbl_speed = lv_label_create(scr);
    lv_obj_set_style_text_font(lbl_speed, &font_roboto_bolditalic_162, 0);
    lv_obj_set_style_text_color(lbl_speed, c_WHITE, 0);

    /* km/h label */
    lbl_kmh = lv_label_create(scr);
    lv_obj_set_style_text_font(lbl_kmh, &font_opensans_regular_28, 0);
    lv_obj_set_style_text_color(lbl_kmh, c_GREY, 0);
    lv_label_set_text(lbl_kmh, "km/h");

    /* gear value */
    lbl_gear_val = lv_label_create(scr);
    lv_obj_set_style_text_font(lbl_gear_val, &font_opensauceone_bold_96, 0);

    /* gear label */
    lbl_gear_lbl = lv_label_create(scr);
    lv_obj_set_style_text_font(lbl_gear_lbl, &font_opensauceone_regular_25, 0);
    lv_obj_set_style_text_color(lbl_gear_lbl, c_WHITE, 0);
    lv_label_set_text(lbl_gear_lbl, "GEAR");
    lv_obj_set_pos(lbl_gear_lbl,
        86 - lv_font_get_glyph_width(&font_opensauceone_regular_25,'G',0)/2,
        57 - 25/2);

    /* strip labels */
    #define MKLBL(var, font, color) \
        var = lv_label_create(scr); \
        lv_obj_set_style_text_font(var, font, 0); \
        lv_obj_set_style_text_color(var, color, 0);

    MKLBL(lbl_odo_label, &font_opensans_regular_20,  c_GREY);
    MKLBL(lbl_odo_val,   &font_opensans_bold_26,     c_WHITE);
    MKLBL(lbl_odo_unit,  &font_opensans_regular_17,  c_GREY);
    MKLBL(lbl_temp_val,  &font_opensans_bold_26,     c_WHITE);
    MKLBL(lbl_volt_val,  &font_opensans_bold_26,     c_WHITE);
    MKLBL(lbl_range_val, &font_opensans_bold_26,     c_WHITE);
    MKLBL(lbl_eco_val,   &font_opensans_bold_26,     c_WHITE);
    MKLBL(lbl_eco_unit,  &font_opensans_regular_17,  c_GREY);
    MKLBL(lbl_time,      &font_opensans_bold_26,     c_WHITE);

    /* dim overlay */
    dim_overlay = lv_obj_create(scr);
    lv_obj_set_size(dim_overlay, W, H);
    lv_obj_set_pos(dim_overlay, 0, 0);
    lv_obj_set_style_bg_color(dim_overlay, lv_color_black(), 0);
    lv_obj_set_style_bg_opa(dim_overlay, LV_OPA_TRANSP, 0);
    lv_obj_set_style_border_width(dim_overlay, 0, 0);
    lv_obj_set_style_radius(dim_overlay, 0, 0);
}

