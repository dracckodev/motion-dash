static void cache_theme(int idx) {
    const dash_theme_t *t = &DASH_THEMES[idx];
    u_BG=t->BG; u_RED=t->RED; u_RED_MED=t->RED_MED;
    u_RED_DIM=t->RED_DIM; u_RED_DARK=t->RED_DARK;
    u_WHITE=t->WHITE; u_GREY=t->GREY;
    c_BG=u32_to_lvc(u_BG); c_RED=u32_to_lvc(u_RED);
    c_RED_MED=u32_to_lvc(u_RED_MED); c_RED_DIM=u32_to_lvc(u_RED_DIM);
    c_RED_DARK=u32_to_lvc(u_RED_DARK); c_WHITE=u32_to_lvc(u_WHITE);
    c_GREY=u32_to_lvc(u_GREY);
    g_tick_contrast = t->tick_contrast;
}

