$ErrorActionPreference = "Stop"

$RepoRoot = Resolve-Path "$PSScriptRoot\.."
$SimDir   = Join-Path $RepoRoot "dash_sim"
$BuildDir = Join-Path $SimDir "build"

Write-Host "Repo root: $RepoRoot"

# Warn if lv_conf.h missing
if (-not (Test-Path "$RepoRoot\lv_conf.h")) {
    Write-Warning "lv_conf.h not found at repo root."
}

# Clean build dir (optional but avoids stale cache issues)
if (Test-Path $BuildDir) {
    Remove-Item $BuildDir -Recurse -Force
}

New-Item -ItemType Directory -Path $BuildDir | Out-Null

# ?????????????????????????????????????????????
# Configure
# ?????????????????????????????????????????????
Write-Host "=== Configuring dash_sim ==="

cmake -S $SimDir -B $BuildDir `
    -DCMAKE_TOOLCHAIN_FILE="C:\Users\draccko\Downloads\motion-dash\rs125_dash_rewrite\vcpkg\scripts\buildsystems\vcpkg.cmake" `
    -DVCPKG_TARGET_TRIPLET=x64-windows

if ($LASTEXITCODE -ne 0) {
    throw "CMake configuration failed"
}

# ?????????????????????????????????????????????
# Build
# ?????????????????????????????????????????????
Write-Host "=== Building ==="

cmake --build $BuildDir --config Release

if ($LASTEXITCODE -ne 0) {
    throw "Build failed"
}

# ?????????????????????????????????????????????
# Find exe
# ?????????????????????????????????????????????
$exe = Get-ChildItem -Path $BuildDir -Recurse -Filter "dash_sim.exe" | Select-Object -First 1

if ($exe) {
    Write-Host "Build successful:"
    Write-Host $exe.FullName
} else {
    Write-Warning "Build succeeded but exe not found (unexpected layout)"
}